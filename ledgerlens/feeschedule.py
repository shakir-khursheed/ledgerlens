"""Fee schedules and money arithmetic.

Everything here is integer paise with explicit half-up rounding. Banker's
rounding (Python's default for round()) silently costs you paise at scale and
is the single most common source of phantom GST breaks.
"""
from __future__ import annotations

from datetime import date, timedelta

from .models import Method

GST_BP = 1800  # 18%, in basis points

#: Current MDR by method, in basis points of gross.
CURRENT_MDR_BP: dict[Method, int] = {
    Method.UPI: 0,
    Method.CARD: 200,
    Method.NETBANKING: 175,
    Method.WALLET: 220,
    Method.INTL_CARD: 300,
}

#: A rate revision that went live mid-quarter. Settlement files generated by
#: the bank before cutover still carry the old rate -- this is the single
#: biggest break family in the generated dataset, and in real life.
LEGACY_MDR_BP: dict[Method, int] = {**CURRENT_MDR_BP, Method.CARD: 230, Method.WALLET: 250}

#: Expected settlement lag in days, by method.
T_PLUS: dict[Method, int] = {
    Method.UPI: 1,
    Method.CARD: 2,
    Method.NETBANKING: 2,
    Method.WALLET: 2,
    Method.INTL_CARD: 5,
}

#: Tolerance (in days) before a late settlement is treated as a real break.
WINDOW_SLACK_DAYS = 1


def mul_bp(amount_paise: int, bp: int) -> int:
    """amount * bp/10000, rounded half-up, in paise."""
    num = amount_paise * bp
    return (num + 5000) // 10000 if num >= 0 else -((-num + 5000) // 10000)


def fee_for(amount_paise: int, method: Method, *, legacy: bool = False) -> tuple[int, int]:
    """Return (fee_paise, gst_paise)."""
    table = LEGACY_MDR_BP if legacy else CURRENT_MDR_BP
    fee = mul_bp(amount_paise, table[method])
    return fee, mul_bp(fee, GST_BP)


def expected_net(amount_paise: int, method: Method, *, legacy: bool = False) -> int:
    fee, gst = fee_for(amount_paise, method, legacy=legacy)
    return amount_paise - fee - gst


def expected_window(captured_on: date, method: Method) -> tuple[date, date]:
    due = captured_on + timedelta(days=T_PLUS[method])
    return due, due + timedelta(days=WINDOW_SLACK_DAYS)
